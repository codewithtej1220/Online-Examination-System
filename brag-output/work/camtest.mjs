const b = await launch({ width: 1400, height: 900, extraArgs: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const logs = [];
await b.send("Runtime.enable");
b.send("Log.enable");
await b.goto("http://localhost:5000/app/", 800);
